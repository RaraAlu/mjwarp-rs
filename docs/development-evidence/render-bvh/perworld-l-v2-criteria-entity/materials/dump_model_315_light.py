#!/usr/bin/env python3
"""Offline 3.15 dumper for the per-world L v2 criteria-entity model input (authoring only).

Why: the criteria entity `render_per_world_light` needs a product-format model dump of
`fixtures/render-bvh/scene-a-light/scene.xml` (the signed spec v3 scene variant, QA-verified).
The dump is test support data, so it lives under `tests/support/render_bvh/light/` and is
NOT written into `fixtures/` (same precedent as the hfield/SDF test-support model dumps).

Version discipline: this dumper runs ONLY on the pinned authoring venv (mujoco 3.15.0, the
same version the reference capture uses). It reuses the verified `model_parity` tooling
(`compile_315` = two mjb saves + sha compare; `dump_model` = the product field dump), and
additionally dumps twice to prove byte-identical output.

Provenance recorded next to the dump:
  - this script sha256, model_parity.py sha256, python/mujoco versions;
  - verbatim command (argv + cwd), input scene sha256/bytes;
  - output sha256/bytes, two-dump byte equality, mjb two-save determinism;
  - `model_file` field note (path/name only, the .mjb is generated and not committed).

Usage (from repo root):
  target/mjwarp-parallel/venv/Scripts/python.exe -B \
    docs/development-evidence/render-bvh/perworld-l-v2-criteria-entity/materials/dump_model_315_light.py
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[5]
sys.path.insert(0, str(REPO / "scripts/authoring/render-bvh"))

import model_parity as mp  # noqa: E402  (offline authoring tooling, pinned venv only)


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--scene", type=pathlib.Path,
                        default=REPO / "fixtures/render-bvh/scene-a-light/scene.xml")
    parser.add_argument("--out", type=pathlib.Path,
                        default=REPO / "tests/support/render_bvh/light/model-315.json")
    parser.add_argument("--provenance-out", type=pathlib.Path,
                        default=REPO / "tests/support/render_bvh/light/model-315.provenance.json")
    parser.add_argument("--work-dir", type=pathlib.Path,
                        default=REPO / "target/render-bvh/criteria-entity-dump")
    args = parser.parse_args()

    scene = args.scene
    work = args.work_dir
    work.mkdir(parents=True, exist_ok=True)
    args.out.parent.mkdir(parents=True, exist_ok=True)

    compiled = mp.compile_315(scene, work)
    dump_a = mp.dump_model(compiled["model"], "dump_model_315_light",
                           "scene-a-light-315.mjb (generated by this dumper; not committed; field is model file name only)")
    text_a = json.dumps(dump_a, ensure_ascii=False, separators=(",", ":")) + "\n"
    dump_b = mp.dump_model(compiled["model"], "dump_model_315_light",
                           "scene-a-light-315.mjb (generated by this dumper; not committed; field is model file name only)")
    text_b = json.dumps(dump_b, ensure_ascii=False, separators=(",", ":")) + "\n"
    deterministic_dump = text_a == text_b
    if not deterministic_dump:
        print("ERROR: two dumps differ byte-wise", file=sys.stderr)
        return 3
    args.out.write_bytes(text_a.encode("utf-8"))

    out_bytes = args.out.read_bytes()
    scene_bytes = scene.read_bytes()
    provenance = {
        "schema": 1,
        "kind": "criteria-entity-model-dump-provenance",
        "dump": {
            "path": args.out.relative_to(REPO).as_posix(),
            "sha256": digest(out_bytes),
            "bytes": len(out_bytes),
            "two_dumps_byte_identical": deterministic_dump,
        },
        "tool": {
            "script": "docs/development-evidence/render-bvh/perworld-l-v2-criteria-entity/materials/dump_model_315_light.py",
            "script_sha256": digest(pathlib.Path(__file__).read_bytes()),
            "model_parity": "scripts/authoring/render-bvh/model_parity.py",
            "model_parity_sha256": digest((REPO / "scripts/authoring/render-bvh/model_parity.py").read_bytes()),
        },
        "command": {"argv": [sys.executable, *sys.argv], "cwd": str(pathlib.Path.cwd())},
        "environment": {
            "python": sys.version.split()[0],
            "mujoco": mp.mujoco.__version__,
            "mujoco_version_int": int(mp.mujoco.mj_version()),
        },
        "input_scene": {
            "path": scene.relative_to(REPO).as_posix(),
            "sha256": digest(scene_bytes),
            "bytes": len(scene_bytes),
        },
        "compile_315": {
            "mjb_sha256": compiled["sha256"],
            "mjb_bytes": compiled["bytes"],
            "two_saves_identical": compiled["deterministic"],
        },
        "model_file_note": "dump_model records `model_file` as a name string only; the .mjb is generated "
                           "under target/ and not committed, so the field does not identify a committed file.",
        "counts": dump_a["counts"],
    }
    provenance_text = json.dumps(provenance, ensure_ascii=False, indent=2) + "\n"
    args.provenance_out.write_bytes(provenance_text.encode("utf-8"))
    print(json.dumps({"dump": provenance["dump"], "scene": provenance["input_scene"],
                      "mujoco": provenance["environment"]["mujoco"],
                      "deterministic_dump": deterministic_dump,
                      "deterministic_compile": compiled["deterministic"]}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
